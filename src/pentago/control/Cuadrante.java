package pentago.control;

/**
 * Enumeración que representa los cuatro cuadrantes de un tablero de juego.
 * 
 * Se numeran de la siguiente manera: de izquierda a derecha y de arriba a abajo.
 *
 * @author <a href="mailto:rmartico@ubu.es">Raúl Marticorena</a>
 * @version 1.0
 */
public enum Cuadrante {
	/** Primero cuadrante: superior izquierdo. */
	SUPERIOR_IZQUIERDO,
	/** Segundo cuadrante: superior derecho. */
	SUPERIOR_DERECHO,
	/** Tercer cuadrante: inferior izquierdo. */
	INFERIOR_IZQUIERDO,
	/** Cuarto cuadrante: inferior derecho. */
	INFERIOR_DERECHO;
}
